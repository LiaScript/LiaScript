// Words for reading formulas aloud, see ./index.ts. Every map is looked up by
// the KaTeX token (command or character); open, close, bin and rel are tried
// first for their atom family, then symbols. An empty string drops the token.

type Words = Record<string, string>

// a word in singular and plural, the form is chosen by Intl.PluralRules
type Forms = Record<string, { one: string; other: string }>

const GREEK =
  'alpha beta gamma delta epsilon zeta eta theta iota kappa lambda mu nu xi omicron pi rho sigma tau upsilon phi chi psi omega'.split(
    ' '
  )

// \alpha, \Alpha and the \var... variants, capital(name) names the upper case
export const greek = (capital: (name: string) => string) => {
  const map: Words = {}
  for (const name of GREEK) {
    map['\\' + name] = name
    map['\\var' + name] = name
    map['\\' + name[0].toUpperCase() + name.slice(1)] = capital(name)
  }
  return map
}

